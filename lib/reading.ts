const conditions = String.raw`(?:연\s*)?\d+(?:\.\d+)?(?:~\d+(?:\.\d+)?)?%|\d+(?:개월|년)\s*이내`;
const pattern = new RegExp(`${date}|${amount}|${conditions}|${phrases.join('|')}`, 'g');
export function readingTokens(text: string) {
  const tokens: { text: string; kind: 'text' | 'date' | 'important' }[] = [];
  let cursor = 0;
  for (const match of text.matchAll(pattern)) {
    const index = match.index!;
    if (index > cursor) tokens.push({ text: text.slice(cursor, index), kind: 'text' });
    tokens.push({ text: match[0], kind: /^\d{4}년/.test(match[0]) ? 'date' : 'important' });
    cursor = index + match[0].length;
  }
  if (cursor < text.length) tokens.push({ text: text.slice(cursor), kind: 'text' });
  return tokens;
}

export function readingParagraphs(text: string) {
  // Break at sentence boundaries only, preserving punctuation, numbers, and wording.
  const sentences = text.split(/(?<=[.!?])(?=\s)/);
  const paragraphs: string[] = [];
  for (let i = 0; i < sentences.length; i += 2) paragraphs.push(sentences.slice(i, i + 2).join(''));
  return paragraphs;
}
